import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
import { HAPTIC_JACKPOT_PATTERN } from '../src/haptics.js';
import { SLOT_UNLOCK_7, SLOT_UNLOCK_9 } from '../src/slots.js';
const executablePath = process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined);
const browser = await chromium.launch({ executablePath, args: process.platform === 'linux' ? ['--no-sandbox'] : [] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.__vib = [];
    navigator.vibrate = pattern => { window.__vib.push(pattern); return true; };
    const saved = JSON.parse(localStorage.getItem('ponpon-settings') || '{}');
    if (saved.collections == null) saved.collections = { 2: 8, 3: 1, 5: 4, 10: 6 };
    if (saved.sound == null) saved.sound = false;
    if (saved.calm == null) saved.calm = true;
    if (saved.vibrate == null) saved.vibrate = true;
    localStorage.setItem('ponpon-settings', JSON.stringify(saved));
  });
  await page.clock.install({ time: Date.UTC(2026, 9, 10, 12) });
  await page.clock.pauseAt(Date.UTC(2026, 9, 10, 12) + 1000);
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5173');
  await page.clock.runFor(50);
  assert.equal(await page.locator('[data-slots]').count(), 0);
  assert.equal(await page.evaluate(() => window.__ponpon.slots), 5);
  assert.deepEqual(await page.evaluate(() => window.__ponpon.collections), { 2: 8, 3: 1, 5: 4, 10: 6, 20: 0 });
  await page.evaluate(amount => window.__ponpon.grant(amount), SLOT_UNLOCK_7 - 1);
  await page.clock.runFor(50);
  assert.equal(await page.evaluate(() => window.__ponpon.slots), 5, 'one point below 7 slots stays on 5 slots');
  await page.evaluate(() => window.__ponpon.grant(1));
  await page.clock.runFor(50);
  assert.equal(await page.evaluate(() => window.__ponpon.slots), 7);
  assert.match(await page.locator('#toast').textContent(), /7 个落袋/);
  assert.equal(await page.locator('#slot-upgrade').isHidden(), false);
  assert.ok((await page.evaluate(() => window.__vib)).some(pattern => JSON.stringify(pattern) === JSON.stringify(HAPTIC_JACKPOT_PATTERN)));
  assert.equal(await page.evaluate(() => window.__ponpon.holdBall()), true);
  await page.evaluate(goal => window.__ponpon.grant(goal - window.__ponpon.score), SLOT_UNLOCK_9);
  await page.clock.runFor(30);
  assert.equal(await page.evaluate(() => window.__ponpon.slots), 7, 'a ball on the table delays the 9-slot switch');
  await page.evaluate(() => window.__ponpon.releaseWave());
  await page.clock.runFor(50);
  assert.equal(await page.evaluate(() => window.__ponpon.slots), 9);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('ponpon-settings')).slots), 9);
  await page.reload();
  await page.clock.runFor(50);
  assert.equal(await page.evaluate(() => window.__ponpon.slots), 5, 'a refresh starts the next round at 5 slots');
  assert.equal(await page.evaluate(() => window.__ponpon.score), 0, 'a refresh starts the next round at score 0');
  assert.equal(await page.evaluate(() => window.__ponpon.keepProgress), false);
  assert.deepEqual(errors, []);
  console.log('PASS: score thresholds upgrade 5→7→9, a live ball waits, vibration and toast fire, and a refresh starts a fresh round.');
} finally { await browser.close(); }
