import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
import { LEADERBOARD_QUALIFY_SCORE } from '../src/leaderboard.js';
const executablePath = process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined);
const browser = await chromium.launch({ executablePath, args: process.platform === 'linux' ? ['--no-sandbox'] : [] });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    const saved = JSON.parse(localStorage.getItem('ponpon-settings') || '{}');
    if (saved.sound == null) saved.sound = false;
    if (saved.vibrate == null) saved.vibrate = false;
    localStorage.setItem('ponpon-settings', JSON.stringify(saved));
  });
  await page.clock.install({ time: Date.UTC(2026, 9, 10, 12) });
  await page.clock.pauseAt(Date.UTC(2026, 9, 10, 12) + 1000);
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5173');
  await page.clock.runFor(50);
  await page.locator('#leaderboard-button').click();
  await page.clock.runFor(30);
  assert.equal(await page.locator('#lb-list .lb-row').count(), 20);
  assert.equal(await page.locator('.lb-name').first().textContent(), 'AAA');
  assert.equal(await page.locator('.lb-score').first().textContent(), await page.evaluate(() => (101220).toLocaleString()));
  assert.equal(await page.locator('.lb-name').nth(19).textContent(), 'Z');
  const firstRead = await page.locator('.lb-score').allTextContents();
  await page.locator('#leaderboard-return').click();
  await page.locator('#leaderboard-button').click();
  assert.deepEqual(await page.locator('.lb-score').allTextContents(), firstRead, 'preset scores do not reshuffle');
  await page.locator('#leaderboard-return').click();
  await page.evaluate(amount => window.__ponpon.grant(amount), LEADERBOARD_QUALIFY_SCORE - 1);
  await page.clock.runFor(40);
  assert.equal(await page.locator('#name-entry').evaluate(el => el.open), false, '49999 does not ask for a name');
  assert.equal(await page.evaluate(() => window.__ponpon.holdBall()), true);
  await page.evaluate(() => window.__ponpon.grant(1));
  await page.clock.runFor(40);
  assert.equal(await page.locator('#name-entry').evaluate(el => el.open), false, 'a live ball delays the name prompt');
  await page.evaluate(() => window.__ponpon.releaseWave());
  await page.clock.runFor(80);
  assert.equal(await page.locator('#name-entry').evaluate(el => el.open), true);
  await page.locator('#player-name').fill('<img src=x>');
  await page.locator('#name-form').locator('button[type="submit"]').click();
  await page.clock.runFor(40);
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('ponpon-leaderboard')).entries);
  assert.equal(stored.length, 1);
  assert.equal(stored[0].name, '<img src=x>');
  assert.equal(stored[0].runId, await page.evaluate(() => window.__ponpon.runId));
  const scoreAtSubmit = await page.evaluate(() => window.__ponpon.score);
  assert.equal(stored[0].score, scoreAtSubmit);
  await page.evaluate(() => window.__ponpon.grant(200000));
  await page.clock.runFor(40);
  await page.locator('#leaderboard-button').click();
  await page.clock.runFor(30);
  assert.equal(await page.locator('#lb-list img').count(), 0);
  assert.equal(await page.locator('.lb-name').first().textContent(), '<img src=x>');
  assert.equal(await page.evaluate(() => document.querySelector('#lb-list').innerHTML.includes('<img')), false);
  const updated = await page.evaluate(() => JSON.parse(localStorage.getItem('ponpon-leaderboard')).entries);
  assert.equal(updated.length, 1, 'the same run updates instead of adding another row');
  assert.equal(updated[0].score, await page.evaluate(() => window.__ponpon.score));
  assert.equal(updated[0].score > scoreAtSubmit, true);
  assert.deepEqual(errors, []);
  console.log('PASS: top 20 presets, delayed name entry, escaped names, and a live score on the same run.');
} finally { await browser.close(); }
